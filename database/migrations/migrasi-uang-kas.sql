-- ================= 1. TABEL CONFIG PER ANGKATAN =================
CREATE TABLE IF NOT EXISTS public.osis_uang_kas_config (
  angkatan_id      bigint PRIMARY KEY REFERENCES public.angkatan (id) ON DELETE RESTRICT,
  nominal_mingguan bigint NOT NULL DEFAULT 2000 CHECK (nominal_mingguan > 0),
  tanggal_mulai    date NOT NULL DEFAULT (date_trunc('week', (now() AT TIME ZONE 'Asia/Jakarta')::date)::date),
  minggu_libur     jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(minggu_libur) = 'array'),
  tarif_riwayat    jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(tarif_riwayat) = 'array'),
  catatan          text NOT NULL DEFAULT '',
  updated_by       bigint REFERENCES public.osis_users (id) ON DELETE SET NULL,
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_uang_kas_config_updated_by
  ON public.osis_uang_kas_config (updated_by);

-- ================= 2. TABEL SETORAN PER ORANG =================
CREATE TABLE IF NOT EXISTS public.osis_uang_kas_setoran (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  angkatan_id bigint NOT NULL REFERENCES public.angkatan (id) ON DELETE RESTRICT,
  nama        text NOT NULL DEFAULT '',
  tanggal     date NOT NULL,
  nominal     bigint NOT NULL CHECK (nominal > 0),
  catatan     text NOT NULL DEFAULT '',
  created_by  bigint REFERENCES public.osis_users (id) ON DELETE SET NULL,
  pengunggah  text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_uang_kas_setoran_ang_tgl
  ON public.osis_uang_kas_setoran (angkatan_id, tanggal DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_uang_kas_setoran_ang_nama
  ON public.osis_uang_kas_setoran (angkatan_id, lower(nama));
CREATE INDEX IF NOT EXISTS idx_uang_kas_setoran_created_by
  ON public.osis_uang_kas_setoran (created_by);

DROP TRIGGER IF EXISTS trg_isi_pengunggah ON public.osis_uang_kas_setoran;
CREATE TRIGGER trg_isi_pengunggah
  BEFORE INSERT ON public.osis_uang_kas_setoran
  FOR EACH ROW EXECUTE FUNCTION public.isi_pengunggah();

-- ================= 3. RLS & HAK TABEL =================
ALTER TABLE public.osis_uang_kas_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.osis_uang_kas_setoran ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.osis_uang_kas_config, public.osis_uang_kas_setoran FROM PUBLIC, anon;
GRANT SELECT ON TABLE public.osis_uang_kas_config, public.osis_uang_kas_setoran TO authenticated;
GRANT ALL ON TABLE public.osis_uang_kas_config, public.osis_uang_kas_setoran TO service_role;

DROP POLICY IF EXISTS uang_kas_config_osis_select ON public.osis_uang_kas_config;
CREATE POLICY uang_kas_config_osis_select ON public.osis_uang_kas_config
  FOR SELECT TO authenticated
  USING (
    (SELECT public.osis_id_dari_auth()) IS NOT NULL
    AND (
      (SELECT public.osis_lintas_angkatan((SELECT public.osis_id_dari_auth())))
      OR angkatan_id = (SELECT public.osis_angkatan_dari_auth())
    )
  );

DROP POLICY IF EXISTS uang_kas_setoran_osis_select ON public.osis_uang_kas_setoran;
CREATE POLICY uang_kas_setoran_osis_select ON public.osis_uang_kas_setoran
  FOR SELECT TO authenticated
  USING (
    (SELECT public.osis_id_dari_auth()) IS NOT NULL
    AND (
      (SELECT public.osis_lintas_angkatan((SELECT public.osis_id_dari_auth())))
      OR angkatan_id = (SELECT public.osis_angkatan_dari_auth())
    )
  );

-- ================= 4. RPC TULIS (SECURITY DEFINER) =================
CREATE OR REPLACE FUNCTION public.simpan_uang_kas_config(
  p_user_id          bigint,
  p_nominal_mingguan bigint,
  p_tanggal_mulai    date,
  p_minggu_libur     jsonb DEFAULT '[]'::jsonb,
  p_tarif_riwayat    jsonb DEFAULT '[]'::jsonb,
  p_catatan          text DEFAULT '',
  p_angkatan_id      bigint DEFAULT NULL
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_ang      bigint;
  v_mulai    date;
  v_libur    jsonb := '[]'::jsonb;
  v_riwayat  jsonb := '[]'::jsonb;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN RETURN 'ERR_NO_AUTH'; END IF;
  END IF;
  IF NOT public.osis_bisa(p_user_id, 'uang-kas') THEN RETURN 'ERR_NO_AUTH'; END IF;

  v_ang := public.osis_target_angkatan(p_user_id, p_angkatan_id);
  IF v_ang IS NULL THEN RETURN 'ERR_NO_AUTH'; END IF;
  IF COALESCE(p_nominal_mingguan, 0) <= 0 THEN RETURN 'ERR_NOMINAL'; END IF;
  IF p_tanggal_mulai IS NULL THEN RETURN 'ERR_NO_TANGGAL'; END IF;

  v_mulai := date_trunc('week', p_tanggal_mulai)::date;

  IF p_minggu_libur IS NOT NULL AND jsonb_typeof(p_minggu_libur) = 'array' THEN
    SELECT COALESCE(jsonb_agg(to_char(s_tgl, 'YYYY-MM-DD') ORDER BY s_tgl), '[]'::jsonb)
      INTO v_libur
      FROM (
        SELECT DISTINCT date_trunc('week', (el #>> '{}')::date)::date AS s_tgl
          FROM jsonb_array_elements(p_minggu_libur) AS el
         WHERE (el #>> '{}') ~ '^\d{4}-\d{2}-\d{2}$'
      ) sub;
  END IF;

  IF p_tarif_riwayat IS NOT NULL AND jsonb_typeof(p_tarif_riwayat) = 'array' THEN
    SELECT COALESCE(
      jsonb_agg(
        jsonb_build_object('mulai', to_char(m_tgl, 'YYYY-MM-DD'), 'nominal', nom)
        ORDER BY m_tgl
      ),
      '[]'::jsonb
    )
      INTO v_riwayat
      FROM (
        SELECT DISTINCT ON (date_trunc('week', (el->>'mulai')::date)::date)
               date_trunc('week', (el->>'mulai')::date)::date AS m_tgl,
               (el->>'nominal')::bigint AS nom
          FROM jsonb_array_elements(p_tarif_riwayat) WITH ORDINALITY AS t(el, ord)
         WHERE jsonb_typeof(el) = 'object'
           AND COALESCE(el->>'mulai', '') ~ '^\d{4}-\d{2}-\d{2}$'
           AND COALESCE(el->>'nominal', '') ~ '^\d+$'
           AND (el->>'nominal')::bigint > 0
         ORDER BY date_trunc('week', (el->>'mulai')::date)::date, ord DESC
      ) sub;
  END IF;

  INSERT INTO public.osis_uang_kas_config (
    angkatan_id, nominal_mingguan, tanggal_mulai, minggu_libur, tarif_riwayat, catatan, updated_by, updated_at
  ) VALUES (
    v_ang, p_nominal_mingguan, v_mulai, v_libur, v_riwayat, left(btrim(COALESCE(p_catatan, '')), 300), p_user_id, now()
  )
  ON CONFLICT (angkatan_id) DO UPDATE SET
    nominal_mingguan = EXCLUDED.nominal_mingguan,
    tanggal_mulai    = EXCLUDED.tanggal_mulai,
    minggu_libur     = EXCLUDED.minggu_libur,
    tarif_riwayat    = EXCLUDED.tarif_riwayat,
    catatan          = EXCLUDED.catatan,
    updated_by       = p_user_id,
    updated_at       = now();

  RETURN 'OK';
END;
$function$;

CREATE OR REPLACE FUNCTION public.toggle_uang_kas_libur(
  p_user_id     bigint,
  p_minggu      date,
  p_libur       boolean DEFAULT NULL,
  p_angkatan_id bigint DEFAULT NULL
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_ang      bigint;
  v_senin    text;
  v_cur      jsonb;
  v_ada      boolean;
  v_jadikan  boolean;
  v_baru     jsonb;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN RETURN 'ERR_NO_AUTH'; END IF;
  END IF;
  IF NOT public.osis_bisa(p_user_id, 'uang-kas') THEN RETURN 'ERR_NO_AUTH'; END IF;

  v_ang := public.osis_target_angkatan(p_user_id, p_angkatan_id);
  IF v_ang IS NULL THEN RETURN 'ERR_NO_AUTH'; END IF;
  IF p_minggu IS NULL THEN RETURN 'ERR_NO_TANGGAL'; END IF;

  v_senin := to_char(date_trunc('week', p_minggu)::date, 'YYYY-MM-DD');

  INSERT INTO public.osis_uang_kas_config (angkatan_id, updated_by)
  VALUES (v_ang, p_user_id)
  ON CONFLICT (angkatan_id) DO NOTHING;

  SELECT COALESCE(minggu_libur, '[]'::jsonb)
    INTO v_cur
    FROM public.osis_uang_kas_config
   WHERE angkatan_id = v_ang
   FOR UPDATE;

  SELECT EXISTS (
    SELECT 1 FROM jsonb_array_elements_text(v_cur) AS t(val) WHERE val = v_senin
  ) INTO v_ada;

  v_jadikan := COALESCE(p_libur, NOT v_ada);

  IF v_jadikan THEN
    SELECT COALESCE(jsonb_agg(val ORDER BY val), '[]'::jsonb)
      INTO v_baru
      FROM (
        SELECT DISTINCT val FROM (
          SELECT jsonb_array_elements_text(v_cur) AS val
          UNION ALL
          SELECT v_senin
        ) u
      ) s;
  ELSE
    SELECT COALESCE(jsonb_agg(val ORDER BY val), '[]'::jsonb)
      INTO v_baru
      FROM (
        SELECT val FROM jsonb_array_elements_text(v_cur) AS t(val)
         WHERE val <> v_senin
      ) s;
  END IF;

  UPDATE public.osis_uang_kas_config
     SET minggu_libur = v_baru,
         updated_by   = p_user_id,
         updated_at   = now()
   WHERE angkatan_id = v_ang;

  RETURN 'OK';
END;
$function$;

CREATE OR REPLACE FUNCTION public.buat_uang_kas_setoran(
  p_user_id     bigint,
  p_nama        text,
  p_tanggal     date,
  p_nominal     bigint,
  p_catatan     text DEFAULT '',
  p_angkatan_id bigint DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  nid   bigint;
  v_ang bigint;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN RETURN -1; END IF;
  END IF;
  IF NOT public.osis_bisa(p_user_id, 'uang-kas') THEN RETURN -1; END IF;

  v_ang := public.osis_target_angkatan(p_user_id, p_angkatan_id);
  IF v_ang IS NULL THEN RETURN -1; END IF;
  IF p_tanggal IS NULL THEN RETURN -2; END IF;

  p_nama := left(btrim(COALESCE(p_nama, '')), 80);
  IF p_nama = '' THEN RETURN -3; END IF;
  IF COALESCE(p_nominal, 0) <= 0 THEN RETURN -4; END IF;

  INSERT INTO public.osis_uang_kas_setoran (
    angkatan_id, nama, tanggal, nominal, catatan, created_by
  ) VALUES (
    v_ang, p_nama, p_tanggal, p_nominal, left(btrim(COALESCE(p_catatan, '')), 300), p_user_id
  ) RETURNING id INTO nid;

  RETURN nid;
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_uang_kas_setoran(
  p_user_id bigint,
  p_id      bigint,
  p_nama    text,
  p_tanggal date,
  p_nominal bigint,
  p_catatan text DEFAULT ''
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_ang bigint;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN RETURN 'ERR_NO_AUTH'; END IF;
  END IF;
  IF NOT public.osis_bisa(p_user_id, 'uang-kas') THEN RETURN 'ERR_NO_AUTH'; END IF;

  SELECT angkatan_id INTO v_ang FROM public.osis_uang_kas_setoran WHERE id = p_id;
  IF NOT FOUND THEN RETURN 'ERR_NOT_FOUND'; END IF;
  IF NOT public.osis_boleh_angkatan(p_user_id, v_ang) THEN RETURN 'ERR_NO_AUTH'; END IF;

  IF p_tanggal IS NULL THEN RETURN 'ERR_NO_TANGGAL'; END IF;
  p_nama := left(btrim(COALESCE(p_nama, '')), 80);
  IF p_nama = '' THEN RETURN 'ERR_NO_NAMA'; END IF;
  IF COALESCE(p_nominal, 0) <= 0 THEN RETURN 'ERR_NOMINAL'; END IF;

  UPDATE public.osis_uang_kas_setoran
     SET nama       = p_nama,
         tanggal    = p_tanggal,
         nominal    = p_nominal,
         catatan    = left(btrim(COALESCE(p_catatan, '')), 300),
         updated_at = now()
   WHERE id = p_id;

  RETURN 'OK';
END;
$function$;

CREATE OR REPLACE FUNCTION public.hapus_uang_kas_setoran(
  p_user_id bigint,
  p_id      bigint
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_ang bigint;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN RETURN 'ERR_NO_AUTH'; END IF;
  END IF;
  IF NOT public.osis_bisa(p_user_id, 'uang-kas') THEN RETURN 'ERR_NO_AUTH'; END IF;

  SELECT angkatan_id INTO v_ang FROM public.osis_uang_kas_setoran WHERE id = p_id;
  IF NOT FOUND THEN RETURN 'ERR_NOT_FOUND'; END IF;
  IF NOT public.osis_boleh_angkatan(p_user_id, v_ang) THEN RETURN 'ERR_NO_AUTH'; END IF;

  DELETE FROM public.osis_uang_kas_setoran WHERE id = p_id;
  RETURN 'OK';
END;
$function$;

