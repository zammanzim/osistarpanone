   SET halaman = array_append(halaman, 'uang-kas')
 WHERE lower(jabatan) = 'bendahara'
   AND NOT ('uang-kas' = ANY(halaman));

UPDATE public.site_content
   SET nilai = (
     nilai::jsonb || jsonb_build_array(
       jsonb_build_object(
         'href', 'uang-kas',
         'icon', 'fa-solid fa-coins',
         'label', 'Uang Kas',
         'super', false,
         'grup', 'Bendahara'
       )
     )
   )::text,
       updated_at = now()
 WHERE kunci = 'sidebar_menu'
   AND jsonb_typeof(nilai::jsonb) = 'array'
   AND NOT EXISTS (
     SELECT 1
       FROM jsonb_array_elements(nilai::jsonb) AS el
      WHERE lower(COALESCE(el->>'href', '')) IN ('uang-kas', 'uang-kas.html')
   );

COMMIT;
