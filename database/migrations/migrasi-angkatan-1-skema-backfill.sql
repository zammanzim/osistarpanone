-- ================= 3. BACKFILL DATA LAMA =================
DO $$
DECLARE
  v_arsip_id bigint;
  v_j3_id    bigint;
  v_j4_id    bigint;
  v_j5_id    bigint;
BEGIN
  SELECT id INTO v_arsip_id FROM public.angkatan WHERE kode = 'ARSIP-2010-2024';
  SELECT id INTO v_j3_id    FROM public.angkatan WHERE kode = 'ADIABI-3';
  SELECT id INTO v_j4_id    FROM public.angkatan WHERE kode = 'ADIABI-4';
  SELECT id INTO v_j5_id    FROM public.angkatan WHERE kode = 'ADIABI-5';

  IF v_arsip_id IS NULL OR v_j3_id IS NULL OR v_j4_id IS NULL OR v_j5_id IS NULL THEN
    RAISE EXCEPTION 'Seed master angkatan tidak lengkap';
  END IF;

  -- osis_users: petakan teks angkatan ('ADIABI JILID 3', 'ADIABI JILID 4', dst); 'PEMBINA' tetap NULL
  UPDATE public.osis_users u
     SET angkatan_id = a.id,
         angkatan    = a.nama
    FROM public.angkatan a
   WHERE u.angkatan_id IS NULL
     AND upper(btrim(COALESCE(u.angkatan, ''))) <> 'PEMBINA'
     AND (
       upper(btrim(COALESCE(u.angkatan, ''))) = upper(a.nama)
       OR upper(btrim(COALESCE(u.angkatan, ''))) = upper(a.kode)
     );

  -- anggota: berdasarkan tahun (2025->Jilid 3, 2026->Jilid 4, 2027->Jilid 5, <2025->Arsip)
  UPDATE public.anggota
     SET angkatan_id = CASE
       WHEN tahun = 2025 THEN v_j3_id
       WHEN tahun = 2026 THEN v_j4_id
       WHEN tahun = 2027 THEN v_j5_id
       WHEN tahun IS NULL OR tahun < 2025 THEN v_arsip_id
       ELSE v_j4_id
     END
   WHERE angkatan_id IS NULL;

  -- Data operasional periode berjalan -> ADIABI JILID 4
  UPDATE public.osis_kas             SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.osis_saldo_awal      SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.osis_tabungan        SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.osis_absensi         SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.osis_absensi_qr_sesi SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.sekbid_agenda        SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.program              SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.rapat_notulensi      SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.informasi            SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.osis_dokumen         SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.poster               SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.wawancara_calon      SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.wawancara_sesi       SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;
  UPDATE public.wawancara_pertanyaan SET angkatan_id = v_j4_id WHERE angkatan_id IS NULL;

  -- Monitoring OSIS
  UPDATE public.osis_visitor v
     SET angkatan_id = u.angkatan_id
    FROM public.osis_users u
   WHERE v.osis_user_id = u.id
     AND v.angkatan_id IS NULL
     AND u.angkatan_id IS NOT NULL;

  UPDATE public.aktivitas a
     SET angkatan_id = u.angkatan_id
    FROM public.osis_users u
   WHERE a.angkatan_id IS NULL
     AND a.user_key = 'osis:' || u.id::text
     AND u.angkatan_id IS NOT NULL;
END $$;

