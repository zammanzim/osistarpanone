-- osis_saldo_awal: PK (periode) -> (angkatan_id, periode)
DO $$
DECLARE
  v_pk_cols smallint;
BEGIN
  SELECT array_length(i.indkey, 1)
    INTO v_pk_cols
    FROM pg_index i
    JOIN pg_class c ON c.oid = i.indrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public'
     AND c.relname = 'osis_saldo_awal'
     AND i.indisprimary;

  IF COALESCE(v_pk_cols, 0) <> 2 THEN
    ALTER TABLE public.osis_saldo_awal DROP CONSTRAINT IF EXISTS osis_saldo_awal_pkey;
    ALTER TABLE public.osis_saldo_awal ADD CONSTRAINT osis_saldo_awal_pkey PRIMARY KEY (angkatan_id, periode);
  END IF;
END $$;

