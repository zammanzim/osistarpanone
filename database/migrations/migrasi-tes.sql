BEGIN;

-- ================= 1. TABEL UTAMA =================
CREATE TABLE IF NOT EXISTS public.osis_tes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  angkatan_id bigint NOT NULL REFERENCES public.angkatan (id) ON DELETE RESTRICT,
  judul       text NOT NULL DEFAULT 'Tanpa judul',
  deskripsi   text NOT NULL DEFAULT '',
  kategori    text NOT NULL DEFAULT '',
  status      text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'aktif', 'ditutup')),
  pengaturan  jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(pengaturan) = 'object'),
  created_by  bigint REFERENCES public.osis_users (id) ON DELETE SET NULL,
  pengunggah  text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_osis_tes_ang_created
  ON public.osis_tes (angkatan_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_osis_tes_created_by
  ON public.osis_tes (created_by);

DROP TRIGGER IF EXISTS trg_isi_pengunggah ON public.osis_tes;
CREATE TRIGGER trg_isi_pengunggah
  BEFORE INSERT ON public.osis_tes
  FOR EACH ROW EXECUTE FUNCTION public.isi_pengunggah();

-- ================= 2. TABEL SOAL =================
CREATE TABLE IF NOT EXISTS public.osis_tes_soal (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tes_id      bigint NOT NULL REFERENCES public.osis_tes (id) ON DELETE CASCADE,
  angkatan_id bigint NOT NULL REFERENCES public.angkatan (id) ON DELETE RESTRICT,
  urutan      integer NOT NULL DEFAULT 0,
  tipe        text NOT NULL
    CHECK (tipe IN ('pg', 'multi', 'bs', 'isian', 'essay', 'skala', 'bobot')),
  pertanyaan  text NOT NULL DEFAULT '',
  opsi        jsonb NOT NULL DEFAULT '[]'::jsonb,
  kunci       jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(kunci) = 'object'),
  poin        numeric(8,2) NOT NULL DEFAULT 10 CHECK (poin >= 0),
  wajib       boolean NOT NULL DEFAULT true,
  pembahasan  text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_osis_tes_soal_tes_urut
  ON public.osis_tes_soal (tes_id, urutan ASC, id ASC);
CREATE INDEX IF NOT EXISTS idx_osis_tes_soal_ang
  ON public.osis_tes_soal (angkatan_id);

-- ================= 3. TABEL HASIL PESERTA =================
CREATE TABLE IF NOT EXISTS public.osis_tes_hasil (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tes_id          bigint NOT NULL REFERENCES public.osis_tes (id) ON DELETE CASCADE,
  angkatan_id     bigint NOT NULL REFERENCES public.angkatan (id) ON DELETE RESTRICT,
  user_id         bigint NOT NULL REFERENCES public.osis_users (id) ON DELETE CASCADE,
  jawaban         jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(jawaban) = 'object'),
  penilaian       jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(penilaian) = 'object'),
  skor_otomatis   numeric(10,2) NOT NULL DEFAULT 0,
  skor_manual     numeric(10,2) NOT NULL DEFAULT 0,
  skor_total      numeric(10,2) NOT NULL DEFAULT 0,
  skor_maks       numeric(10,2) NOT NULL DEFAULT 0,
  status          text NOT NULL DEFAULT 'selesai'
    CHECK (status IN ('menunggu_koreksi', 'selesai')),
  catatan_koreksi text NOT NULL DEFAULT '',
  dikoreksi_oleh  bigint REFERENCES public.osis_users (id) ON DELETE SET NULL,
  percobaan_ke    integer NOT NULL DEFAULT 1 CHECK (percobaan_ke >= 1),
  mulai_at        timestamptz NULL,
  selesai_at      timestamptz NOT NULL DEFAULT now(),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT osis_tes_hasil_tes_user_key UNIQUE (tes_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_osis_tes_hasil_tes_selesai
  ON public.osis_tes_hasil (tes_id, selesai_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_osis_tes_hasil_user
  ON public.osis_tes_hasil (user_id);
CREATE INDEX IF NOT EXISTS idx_osis_tes_hasil_ang
  ON public.osis_tes_hasil (angkatan_id);
CREATE INDEX IF NOT EXISTS idx_osis_tes_hasil_dikoreksi
  ON public.osis_tes_hasil (dikoreksi_oleh);

-- ================= 4. RLS & HAK TABEL =================
-- Semua akses baca/tulis lewat RPC SECURITY DEFINER biar kolom kunci & hasil
-- peserta lain tidak pernah bocor lewat SELECT langsung.
ALTER TABLE public.osis_tes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.osis_tes_soal ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.osis_tes_hasil ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.osis_tes, public.osis_tes_soal, public.osis_tes_hasil
  FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.osis_tes, public.osis_tes_soal, public.osis_tes_hasil
  TO service_role;

DROP POLICY IF EXISTS osis_tes_select_policy ON public.osis_tes;
CREATE POLICY osis_tes_select_policy ON public.osis_tes
  FOR SELECT TO authenticated
  USING (
    (SELECT public.osis_id_dari_auth()) IS NOT NULL
    AND (
      (SELECT public.osis_lintas_angkatan((SELECT public.osis_id_dari_auth())))
      OR angkatan_id = (SELECT public.osis_angkatan_dari_auth())
    )
    AND (
      status <> 'draft'
      OR (SELECT public.osis_bisa((SELECT public.osis_id_dari_auth()), 'tes'))
    )
  );

DROP POLICY IF EXISTS osis_tes_soal_select_policy ON public.osis_tes_soal;
CREATE POLICY osis_tes_soal_select_policy ON public.osis_tes_soal
  FOR SELECT TO authenticated
  USING (
    (SELECT public.osis_id_dari_auth()) IS NOT NULL
    AND (SELECT public.osis_bisa((SELECT public.osis_id_dari_auth()), 'tes'))
    AND (
      (SELECT public.osis_lintas_angkatan((SELECT public.osis_id_dari_auth())))
      OR angkatan_id = (SELECT public.osis_angkatan_dari_auth())
    )
  );

DROP POLICY IF EXISTS osis_tes_hasil_select_policy ON public.osis_tes_hasil;
CREATE POLICY osis_tes_hasil_select_policy ON public.osis_tes_hasil
  FOR SELECT TO authenticated
  USING (
    (SELECT public.osis_id_dari_auth()) IS NOT NULL
    AND (
      user_id = (SELECT public.osis_id_dari_auth())
      OR (SELECT public.osis_bisa((SELECT public.osis_id_dari_auth()), 'tes'))
    )
    AND (
      (SELECT public.osis_lintas_angkatan((SELECT public.osis_id_dari_auth())))
      OR angkatan_id = (SELECT public.osis_angkatan_dari_auth())
    )
  );

