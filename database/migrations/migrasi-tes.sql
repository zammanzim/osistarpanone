CREATE OR REPLACE FUNCTION public.tes_daftar(
  p_user_id     bigint,
  p_angkatan_id bigint DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_kelola boolean := false;
  v_lintas boolean := false;
  v_ang    bigint;
  v_res    jsonb;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN
      RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
    END IF;
  END IF;

  IF p_angkatan_id IS NOT NULL AND NOT public.osis_boleh_angkatan(p_user_id, p_angkatan_id) THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;

  v_kelola := public.osis_bisa(p_user_id, 'tes');
  v_lintas := public.osis_lintas_angkatan(p_user_id);
  SELECT angkatan_id INTO v_ang FROM public.osis_users WHERE id = p_user_id;

  IF NOT v_lintas AND v_ang IS NULL THEN
    RETURN '[]'::jsonb;
  END IF;

  SELECT COALESCE(jsonb_agg(row_to_json(q)), '[]'::jsonb)
    INTO v_res
    FROM (
      SELECT
        t.id,
        t.angkatan_id,
        t.judul,
        t.deskripsi,
        t.kategori,
        t.status,
        t.pengaturan,
        t.created_by,
        t.pengunggah,
        t.created_at,
        t.updated_at,
        (SELECT count(*)::int FROM public.osis_tes_soal s WHERE s.tes_id = t.id) AS soal_count,
        (SELECT COALESCE(sum(s.poin), 0) FROM public.osis_tes_soal s WHERE s.tes_id = t.id) AS poin_maks,
        CASE WHEN v_kelola THEN
          (SELECT count(*)::int FROM public.osis_tes_hasil h WHERE h.tes_id = t.id)
        ELSE NULL END AS peserta_count,
        CASE WHEN v_kelola THEN
          (SELECT count(*)::int FROM public.osis_tes_hasil h WHERE h.tes_id = t.id AND h.status = 'menunggu_koreksi')
        ELSE NULL END AS menunggu_koreksi_count,
        (
          SELECT jsonb_build_object(
            'id', h.id,
            'status', h.status,
            'skor_total', CASE
              WHEN v_kelola OR COALESCE((t.pengaturan->>'tampil_nilai')::boolean, true) THEN h.skor_total
              ELSE NULL
            END,
            'skor_maks', h.skor_maks,
            'percobaan_ke', h.percobaan_ke,
            'selesai_at', h.selesai_at
          )
          FROM public.osis_tes_hasil h
          WHERE h.tes_id = t.id AND h.user_id = p_user_id
          LIMIT 1
        ) AS saya_hasil
      FROM public.osis_tes t
      WHERE (
        (v_lintas AND (p_angkatan_id IS NULL OR t.angkatan_id = p_angkatan_id))
        OR (NOT v_lintas AND t.angkatan_id = v_ang)
      )
        AND (v_kelola OR t.status IN ('aktif', 'ditutup'))
      ORDER BY
        CASE t.status WHEN 'aktif' THEN 0 WHEN 'draft' THEN 1 ELSE 2 END,
        t.created_at DESC,
        t.id DESC
    ) q;

  RETURN v_res;
END;
$function$;

CREATE OR REPLACE FUNCTION public.tes_buka(
  p_user_id    bigint,
  p_tes_id     bigint,
  p_untuk_edit boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_tes          public.osis_tes%ROWTYPE;
  v_hasil        public.osis_tes_hasil%ROWTYPE;
  v_has_hasil    boolean := false;
  v_kelola       boolean := false;
  v_tampil_nilai boolean := true;
  v_tampil_kunci boolean := false;
  v_show_kunci   boolean := false;
  v_soal         jsonb;
  v_hasil_json   jsonb := NULL;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN
      RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
    END IF;
  END IF;

  SELECT * INTO v_tes FROM public.osis_tes WHERE id = p_tes_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'ERR_NOT_FOUND');
  END IF;

  IF NOT public.osis_boleh_angkatan(p_user_id, v_tes.angkatan_id) THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;

  v_kelola := public.osis_bisa(p_user_id, 'tes');
  IF p_untuk_edit AND NOT v_kelola THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;
  IF v_tes.status = 'draft' AND NOT v_kelola THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;

  SELECT * INTO v_hasil
    FROM public.osis_tes_hasil
   WHERE tes_id = p_tes_id AND user_id = p_user_id
   LIMIT 1;
  v_has_hasil := FOUND;

  v_tampil_nilai := COALESCE((v_tes.pengaturan->>'tampil_nilai')::boolean, true);
  v_tampil_kunci := COALESCE((v_tes.pengaturan->>'tampil_kunci')::boolean, false);
  v_show_kunci := p_untuk_edit OR (v_has_hasil AND v_tampil_kunci);

  SELECT COALESCE(jsonb_agg(row_to_json(q)), '[]'::jsonb)
    INTO v_soal
    FROM (
      SELECT
        s.id,
        s.tes_id,
        s.urutan,
        s.tipe,
        s.pertanyaan,
        CASE
          WHEN NOT v_show_kunci AND s.tipe = 'bobot' AND jsonb_typeof(s.opsi) = 'array' THEN
            COALESCE((SELECT jsonb_agg(el - 'poin') FROM jsonb_array_elements(s.opsi) AS el), '[]'::jsonb)
          ELSE s.opsi
        END AS opsi,
        s.poin,
        s.wajib,
        CASE WHEN v_show_kunci THEN s.kunci ELSE NULL END AS kunci,
        CASE WHEN v_show_kunci THEN s.pembahasan ELSE NULL END AS pembahasan
      FROM public.osis_tes_soal s
      WHERE s.tes_id = p_tes_id
      ORDER BY s.urutan ASC, s.id ASC
    ) q;

  IF v_has_hasil THEN
    v_hasil_json := jsonb_build_object(
      'id', v_hasil.id,
      'tes_id', v_hasil.tes_id,
      'user_id', v_hasil.user_id,
      'jawaban', v_hasil.jawaban,
      'penilaian', CASE WHEN v_kelola OR v_tampil_kunci THEN v_hasil.penilaian ELSE '{}'::jsonb END,
      'skor_otomatis', CASE WHEN v_kelola OR v_tampil_nilai THEN v_hasil.skor_otomatis ELSE NULL END,
      'skor_manual', CASE WHEN v_kelola OR v_tampil_nilai THEN v_hasil.skor_manual ELSE NULL END,
      'skor_total', CASE WHEN v_kelola OR v_tampil_nilai THEN v_hasil.skor_total ELSE NULL END,
      'skor_maks', v_hasil.skor_maks,
      'status', v_hasil.status,
      'catatan_koreksi', v_hasil.catatan_koreksi,
      'percobaan_ke', v_hasil.percobaan_ke,
      'mulai_at', v_hasil.mulai_at,
      'selesai_at', v_hasil.selesai_at
    );
  END IF;

  RETURN jsonb_build_object(
    'tes', row_to_json(v_tes),
    'soal', v_soal,
    'saya_hasil', v_hasil_json
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.tes_hasil_list(
  p_user_id bigint,
  p_tes_id  bigint
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_tes public.osis_tes%ROWTYPE;
  v_res jsonb;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN
      RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
    END IF;
  END IF;

  IF NOT public.osis_bisa(p_user_id, 'tes') THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;

  SELECT * INTO v_tes FROM public.osis_tes WHERE id = p_tes_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'ERR_NOT_FOUND');
  END IF;

  IF NOT public.osis_boleh_angkatan(p_user_id, v_tes.angkatan_id) THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;

  SELECT COALESCE(jsonb_agg(row_to_json(q)), '[]'::jsonb)
    INTO v_res
    FROM (
      SELECT
        h.id,
        h.tes_id,
        h.user_id,
        COALESCE(NULLIF(btrim(u.nama), ''), u.username, 'Pengurus #' || h.user_id) AS nama,
        COALESCE(u.username, '') AS username,
        COALESCE(u.jabatan, '') AS jabatan,
        h.skor_otomatis,
        h.skor_manual,
        h.skor_total,
        h.skor_maks,
        h.status,
        h.catatan_koreksi,
        h.percobaan_ke,
        h.mulai_at,
        h.selesai_at,
        h.jawaban,
        h.penilaian
      FROM public.osis_tes_hasil h
      LEFT JOIN public.osis_users u ON u.id = h.user_id
      WHERE h.tes_id = p_tes_id
      ORDER BY h.skor_total DESC, h.selesai_at ASC, h.id ASC
    ) q;

  RETURN v_res;
END;
$function$;

CREATE OR REPLACE FUNCTION public.tes_hasil_detail(
  p_user_id  bigint,
  p_hasil_id bigint
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_hasil        public.osis_tes_hasil%ROWTYPE;
  v_tes          public.osis_tes%ROWTYPE;
  v_kelola       boolean := false;
  v_tampil_nilai boolean := true;
  v_tampil_kunci boolean := false;
  v_show_kunci   boolean := false;
  v_peserta      jsonb;
  v_soal         jsonb;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN
      RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
    END IF;
  END IF;

  SELECT * INTO v_hasil FROM public.osis_tes_hasil WHERE id = p_hasil_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'ERR_NOT_FOUND');
  END IF;

  SELECT * INTO v_tes FROM public.osis_tes WHERE id = v_hasil.tes_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'ERR_NOT_FOUND');
  END IF;

  IF NOT public.osis_boleh_angkatan(p_user_id, v_tes.angkatan_id) THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;

  v_kelola := public.osis_bisa(p_user_id, 'tes');
  IF NOT v_kelola AND v_hasil.user_id <> p_user_id THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;

  v_tampil_nilai := COALESCE((v_tes.pengaturan->>'tampil_nilai')::boolean, true);
  v_tampil_kunci := COALESCE((v_tes.pengaturan->>'tampil_kunci')::boolean, false);
  v_show_kunci := v_kelola OR v_tampil_kunci;

  SELECT jsonb_build_object(
    'id', u.id,
    'nama', COALESCE(NULLIF(btrim(u.nama), ''), u.username, 'Pengurus'),
    'username', COALESCE(u.username, ''),
    'jabatan', COALESCE(u.jabatan, '')
  )
    INTO v_peserta
    FROM public.osis_users u
   WHERE u.id = v_hasil.user_id;

  SELECT COALESCE(jsonb_agg(row_to_json(q)), '[]'::jsonb)
    INTO v_soal
    FROM (
      SELECT
        s.id,
        s.tes_id,
        s.urutan,
        s.tipe,
        s.pertanyaan,
        CASE
          WHEN NOT v_show_kunci AND s.tipe = 'bobot' AND jsonb_typeof(s.opsi) = 'array' THEN
            COALESCE((SELECT jsonb_agg(el - 'poin') FROM jsonb_array_elements(s.opsi) AS el), '[]'::jsonb)
          ELSE s.opsi
        END AS opsi,
        s.poin,
        s.wajib,
        CASE WHEN v_show_kunci THEN s.kunci ELSE NULL END AS kunci,
        CASE WHEN v_show_kunci THEN s.pembahasan ELSE NULL END AS pembahasan
      FROM public.osis_tes_soal s
      WHERE s.tes_id = v_tes.id
      ORDER BY s.urutan ASC, s.id ASC
    ) q;

  RETURN jsonb_build_object(
    'tes', row_to_json(v_tes),
    'peserta', COALESCE(v_peserta, jsonb_build_object('id', v_hasil.user_id, 'nama', 'Pengurus #' || v_hasil.user_id)),
    'soal', v_soal,
    'hasil', jsonb_build_object(
      'id', v_hasil.id,
      'tes_id', v_hasil.tes_id,
      'user_id', v_hasil.user_id,
      'jawaban', v_hasil.jawaban,
      'penilaian', CASE WHEN v_kelola OR v_tampil_kunci THEN v_hasil.penilaian ELSE '{}'::jsonb END,
      'skor_otomatis', CASE WHEN v_kelola OR v_tampil_nilai THEN v_hasil.skor_otomatis ELSE NULL END,
      'skor_manual', CASE WHEN v_kelola OR v_tampil_nilai THEN v_hasil.skor_manual ELSE NULL END,
      'skor_total', CASE WHEN v_kelola OR v_tampil_nilai THEN v_hasil.skor_total ELSE NULL END,
      'skor_maks', v_hasil.skor_maks,
      'status', v_hasil.status,
      'catatan_koreksi', v_hasil.catatan_koreksi,
      'percobaan_ke', v_hasil.percobaan_ke,
      'mulai_at', v_hasil.mulai_at,
      'selesai_at', v_hasil.selesai_at
    )
  );
END;
$function$;

