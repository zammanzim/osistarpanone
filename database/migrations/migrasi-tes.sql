CREATE OR REPLACE FUNCTION public.submit_tes(
  p_user_id  bigint,
  p_tes_id   bigint,
  p_jawaban  jsonb DEFAULT '{}'::jsonb,
  p_mulai_at timestamptz DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_tes          public.osis_tes%ROWTYPE;
  v_kelola       boolean := false;
  v_boleh_ulang  boolean := true;
  v_tampil_nilai boolean := true;
  v_ada_hasil    boolean := false;
  v_soal         record;
  v_ans          jsonb;
  v_ans_str      text;
  v_ans_arr      text[];
  v_key_str      text;
  v_key_arr      text[];
  v_terima_arr   text[];
  v_hit          integer;
  v_wrong        integer;
  v_tot_key      integer;
  v_parsial      boolean;
  v_poin         numeric(10,2);
  v_maks_opsi    numeric(10,2);
  v_ok           boolean;
  v_skor_auto    numeric(10,2) := 0;
  v_skor_maks    numeric(10,2) := 0;
  v_has_manual   boolean := false;
  v_clean_jwb    jsonb := '{}'::jsonb;
  v_penilaian    jsonb := '{}'::jsonb;
  v_status_hasil text;
  v_hasil_id     bigint;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN
      RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
    END IF;
  END IF;

  SELECT * INTO v_tes FROM public.osis_tes WHERE id = p_tes_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'ERR_NOT_FOUND');
  END IF;

  IF NOT public.osis_boleh_angkatan(p_user_id, v_tes.angkatan_id) THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;

  v_kelola := public.osis_bisa(p_user_id, 'tes');
  IF v_tes.status <> 'aktif' THEN
    RETURN jsonb_build_object('error', 'ERR_TES_TUTUP');
  END IF;

  v_boleh_ulang := COALESCE((v_tes.pengaturan->>'boleh_ulang')::boolean, true);
  v_tampil_nilai := COALESCE((v_tes.pengaturan->>'tampil_nilai')::boolean, true);

  SELECT EXISTS (
    SELECT 1 FROM public.osis_tes_hasil WHERE tes_id = p_tes_id AND user_id = p_user_id
  ) INTO v_ada_hasil;

  IF v_ada_hasil AND NOT v_boleh_ulang THEN
    RETURN jsonb_build_object('error', 'ERR_SUDAH_MENGERJAKAN');
  END IF;

  IF p_jawaban IS NULL OR jsonb_typeof(p_jawaban) <> 'object' THEN
    p_jawaban := '{}'::jsonb;
  END IF;

  FOR v_soal IN
    SELECT * FROM public.osis_tes_soal
     WHERE tes_id = p_tes_id
     ORDER BY urutan ASC, id ASC
  LOOP
    v_ans := p_jawaban -> (v_soal.id::text);
    v_poin := 0;
    v_ok := NULL;

    IF v_soal.tipe = 'pg' THEN
      IF jsonb_typeof(v_ans) IN ('string', 'number') THEN
        v_ans_str := btrim(v_ans #>> '{}');
      ELSE
        v_ans_str := '';
      END IF;
      v_clean_jwb := v_clean_jwb || jsonb_build_object(v_soal.id::text, v_ans_str);
      v_key_str := btrim(COALESCE(v_soal.kunci->>'id', ''));
      IF v_key_str <> '' AND v_soal.poin > 0 THEN
        v_ok := (v_ans_str <> '' AND v_ans_str = v_key_str);
        v_poin := CASE WHEN v_ok THEN v_soal.poin ELSE 0 END;
        v_skor_maks := v_skor_maks + v_soal.poin;
        v_skor_auto := v_skor_auto + v_poin;
      END IF;
      v_penilaian := v_penilaian || jsonb_build_object(
        v_soal.id::text,
        jsonb_build_object('poin', v_poin, 'maks', v_soal.poin, 'benar', v_ok, 'manual', false)
      );

    ELSIF v_soal.tipe = 'bs' THEN
      IF jsonb_typeof(v_ans) IN ('string', 'number') THEN
        v_ans_str := lower(btrim(v_ans #>> '{}'));
      ELSE
        v_ans_str := '';
      END IF;
      v_clean_jwb := v_clean_jwb || jsonb_build_object(v_soal.id::text, v_ans_str);
      v_key_str := lower(btrim(COALESCE(v_soal.kunci->>'nilai', '')));
      IF v_key_str IN ('benar', 'salah') AND v_soal.poin > 0 THEN
        v_ok := (v_ans_str = v_key_str);
        v_poin := CASE WHEN v_ok THEN v_soal.poin ELSE 0 END;
        v_skor_maks := v_skor_maks + v_soal.poin;
        v_skor_auto := v_skor_auto + v_poin;
      END IF;
      v_penilaian := v_penilaian || jsonb_build_object(
        v_soal.id::text,
        jsonb_build_object('poin', v_poin, 'maks', v_soal.poin, 'benar', v_ok, 'manual', false)
      );

    ELSIF v_soal.tipe = 'multi' THEN
      v_ans_arr := '{}'::text[];
      IF jsonb_typeof(v_ans) = 'array' THEN
        SELECT COALESCE(array_agg(DISTINCT btrim(x)), '{}'::text[])
          INTO v_ans_arr
          FROM jsonb_array_elements_text(v_ans) AS x
         WHERE btrim(x) <> '';
      END IF;
      v_clean_jwb := v_clean_jwb || jsonb_build_object(v_soal.id::text, to_jsonb(v_ans_arr));

      v_key_arr := '{}'::text[];
      IF jsonb_typeof(v_soal.kunci->'ids') = 'array' THEN
        SELECT COALESCE(array_agg(DISTINCT btrim(x)), '{}'::text[])
          INTO v_key_arr
          FROM jsonb_array_elements_text(v_soal.kunci->'ids') AS x
         WHERE btrim(x) <> '';
      END IF;
      v_tot_key := COALESCE(array_length(v_key_arr, 1), 0);

      IF v_tot_key > 0 AND v_soal.poin > 0 THEN
        SELECT count(*) INTO v_hit
          FROM unnest(v_ans_arr) AS a
         WHERE a = ANY(v_key_arr);
        SELECT count(*) INTO v_wrong
          FROM unnest(v_ans_arr) AS a
         WHERE NOT (a = ANY(v_key_arr));

        v_parsial := COALESCE((v_soal.kunci->>'parsial')::boolean, false);
        v_ok := (v_hit = v_tot_key AND v_wrong = 0);
        IF v_parsial THEN
          v_poin := round(v_soal.poin * GREATEST(0::numeric, (v_hit - v_wrong)::numeric / v_tot_key::numeric), 2);
        ELSE
          v_poin := CASE WHEN v_ok THEN v_soal.poin ELSE 0 END;
        END IF;
        v_skor_maks := v_skor_maks + v_soal.poin;
        v_skor_auto := v_skor_auto + v_poin;
      END IF;
      v_penilaian := v_penilaian || jsonb_build_object(
        v_soal.id::text,
        jsonb_build_object('poin', v_poin, 'maks', v_soal.poin, 'benar', v_ok, 'manual', false)
      );

    ELSIF v_soal.tipe = 'isian' THEN
      IF jsonb_typeof(v_ans) IN ('string', 'number') THEN
        v_ans_str := left(btrim(v_ans #>> '{}'), 500);
      ELSE
        v_ans_str := '';
      END IF;
      v_clean_jwb := v_clean_jwb || jsonb_build_object(v_soal.id::text, v_ans_str);

      v_terima_arr := '{}'::text[];
      IF jsonb_typeof(v_soal.kunci->'terima') = 'array' THEN
        SELECT COALESCE(array_agg(DISTINCT lower(regexp_replace(btrim(x), '\s+', ' ', 'g'))), '{}'::text[])
          INTO v_terima_arr
          FROM jsonb_array_elements_text(v_soal.kunci->'terima') AS x
         WHERE btrim(x) <> '';
      END IF;

      IF COALESCE(array_length(v_terima_arr, 1), 0) > 0 AND v_soal.poin > 0 THEN
        v_key_str := lower(regexp_replace(v_ans_str, '\s+', ' ', 'g'));
        v_ok := (v_key_str <> '' AND v_key_str = ANY(v_terima_arr));
        v_poin := CASE WHEN v_ok THEN v_soal.poin ELSE 0 END;
        v_skor_maks := v_skor_maks + v_soal.poin;
        v_skor_auto := v_skor_auto + v_poin;
      END IF;
      v_penilaian := v_penilaian || jsonb_build_object(
        v_soal.id::text,
        jsonb_build_object('poin', v_poin, 'maks', v_soal.poin, 'benar', v_ok, 'manual', false)
      );

    ELSIF v_soal.tipe = 'essay' THEN
      IF jsonb_typeof(v_ans) = 'string' THEN
        v_ans_str := left(v_ans #>> '{}', 8000);
      ELSE
        v_ans_str := '';
      END IF;
      v_clean_jwb := v_clean_jwb || jsonb_build_object(v_soal.id::text, v_ans_str);
      IF v_soal.poin > 0 THEN
        v_has_manual := true;
        v_skor_maks := v_skor_maks + v_soal.poin;
      END IF;
      v_penilaian := v_penilaian || jsonb_build_object(
        v_soal.id::text,
        jsonb_build_object('poin', 0, 'maks', v_soal.poin, 'benar', NULL, 'manual', true, 'catatan', '')
      );

    ELSIF v_soal.tipe = 'skala' THEN
      IF jsonb_typeof(v_ans) IN ('string', 'number') AND (v_ans #>> '{}') ~ '^-?\d+$' THEN
        v_ans_str := (v_ans #>> '{}');
      ELSE
        v_ans_str := '';
      END IF;
      v_clean_jwb := v_clean_jwb || jsonb_build_object(v_soal.id::text, v_ans_str);
      v_key_str := btrim(COALESCE(v_soal.kunci->>'nilai', ''));
      IF v_key_str <> '' AND v_soal.poin > 0 THEN
        v_ok := (v_ans_str = v_key_str);
        v_poin := CASE WHEN v_ok THEN v_soal.poin ELSE 0 END;
        v_skor_maks := v_skor_maks + v_soal.poin;
        v_skor_auto := v_skor_auto + v_poin;
      END IF;
      v_penilaian := v_penilaian || jsonb_build_object(
        v_soal.id::text,
        jsonb_build_object('poin', v_poin, 'maks', v_soal.poin, 'benar', v_ok, 'manual', false)
      );

    ELSIF v_soal.tipe = 'bobot' THEN
      IF jsonb_typeof(v_ans) IN ('string', 'number') THEN
        v_ans_str := btrim(v_ans #>> '{}');
      ELSE
        v_ans_str := '';
      END IF;
      v_clean_jwb := v_clean_jwb || jsonb_build_object(v_soal.id::text, v_ans_str);
      v_maks_opsi := 0;
      IF jsonb_typeof(v_soal.opsi) = 'array' THEN
        SELECT COALESCE(max(
          CASE WHEN COALESCE(el->>'poin', '') ~ '^\d+(\.\d+)?$' THEN (el->>'poin')::numeric ELSE 0 END
        ), 0)
          INTO v_maks_opsi
          FROM jsonb_array_elements(v_soal.opsi) AS el;
        SELECT COALESCE((
          SELECT CASE WHEN COALESCE(el->>'poin', '') ~ '^\d+(\.\d+)?$' THEN (el->>'poin')::numeric ELSE 0 END
            FROM jsonb_array_elements(v_soal.opsi) AS el
           WHERE el->>'id' = v_ans_str
           LIMIT 1
        ), 0)
          INTO v_poin;
      END IF;
      v_maks_opsi := GREATEST(v_soal.poin, v_maks_opsi);
      IF v_maks_opsi > 0 THEN
        v_skor_maks := v_skor_maks + v_maks_opsi;
        v_skor_auto := v_skor_auto + v_poin;
      END IF;
      v_penilaian := v_penilaian || jsonb_build_object(
        v_soal.id::text,
        jsonb_build_object('poin', v_poin, 'maks', v_maks_opsi, 'benar', NULL, 'manual', false)
      );
    END IF;
  END LOOP;

  v_status_hasil := CASE WHEN v_has_manual THEN 'menunggu_koreksi' ELSE 'selesai' END;

  INSERT INTO public.osis_tes_hasil (
    tes_id, angkatan_id, user_id, jawaban, penilaian,
    skor_otomatis, skor_manual, skor_total, skor_maks,
    status, catatan_koreksi, dikoreksi_oleh, percobaan_ke,
    mulai_at, selesai_at, updated_at
  ) VALUES (
    p_tes_id, v_tes.angkatan_id, p_user_id, v_clean_jwb, v_penilaian,
    v_skor_auto, 0, v_skor_auto, v_skor_maks,
    v_status_hasil, '', NULL, 1,
    p_mulai_at, now(), now()
  )
  ON CONFLICT (tes_id, user_id) DO UPDATE SET
    jawaban         = EXCLUDED.jawaban,
    penilaian       = EXCLUDED.penilaian,
    skor_otomatis   = EXCLUDED.skor_otomatis,
    skor_manual     = 0,
    skor_total      = EXCLUDED.skor_total,
    skor_maks       = EXCLUDED.skor_maks,
    status          = EXCLUDED.status,
    catatan_koreksi = '',
    dikoreksi_oleh  = NULL,
    percobaan_ke    = public.osis_tes_hasil.percobaan_ke + 1,
    mulai_at        = EXCLUDED.mulai_at,
    selesai_at      = now(),
    updated_at      = now()
  RETURNING id INTO v_hasil_id;

  RETURN jsonb_build_object(
    'ok', true,
    'hasil_id', v_hasil_id,
    'status', v_status_hasil,
    'tampil_nilai', v_tampil_nilai,
    'skor_total', CASE WHEN v_kelola OR v_tampil_nilai THEN v_skor_auto ELSE NULL END,
    'skor_maks', v_skor_maks
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.koreksi_tes(
  p_user_id  bigint,
  p_hasil_id bigint,
  p_koreksi  jsonb DEFAULT '{}'::jsonb,
  p_catatan  text DEFAULT '',
  p_selesai  boolean DEFAULT true
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_hasil       public.osis_tes_hasil%ROWTYPE;
  v_tes         public.osis_tes%ROWTYPE;
  v_soal        record;
  v_penilaian   jsonb;
  v_item        jsonb;
  v_kitem       jsonb;
  v_poin        numeric(10,2);
  v_cat         text;
  v_manual      boolean;
  v_benar       boolean;
  v_skor_auto   numeric(10,2) := 0;
  v_skor_manual numeric(10,2) := 0;
  v_skor_maks   numeric(10,2) := 0;
  v_status      text;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN
      RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
    END IF;
  END IF;

  IF NOT public.osis_bisa(p_user_id, 'tes') THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;

  SELECT * INTO v_hasil FROM public.osis_tes_hasil WHERE id = p_hasil_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'ERR_NOT_FOUND');
  END IF;

  SELECT * INTO v_tes FROM public.osis_tes WHERE id = v_hasil.tes_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'ERR_NOT_FOUND');
  END IF;

  IF NOT public.osis_boleh_angkatan(p_user_id, v_tes.angkatan_id) THEN
    RETURN jsonb_build_object('error', 'ERR_NO_AUTH');
  END IF;

  IF p_koreksi IS NULL OR jsonb_typeof(p_koreksi) <> 'object' THEN
    p_koreksi := '{}'::jsonb;
  END IF;

  v_penilaian := COALESCE(v_hasil.penilaian, '{}'::jsonb);

  FOR v_soal IN
    SELECT * FROM public.osis_tes_soal
     WHERE tes_id = v_tes.id
     ORDER BY urutan ASC, id ASC
  LOOP
    v_item := COALESCE(v_penilaian -> (v_soal.id::text), '{}'::jsonb);
    v_manual := COALESCE((v_item->>'manual')::boolean, v_soal.tipe = 'essay');
    v_poin := 0;
    IF COALESCE(v_item->>'poin', '') ~ '^\d+(\.\d+)?$' THEN
      v_poin := (v_item->>'poin')::numeric;
    END IF;
    v_cat := COALESCE(v_item->>'catatan', '');
    v_benar := CASE
      WHEN v_item->>'benar' = 'true' THEN true
      WHEN v_item->>'benar' = 'false' THEN false
      ELSE NULL
    END;

    v_kitem := p_koreksi -> (v_soal.id::text);
    IF jsonb_typeof(v_kitem) = 'object' THEN
      v_manual := true;
      IF COALESCE(v_kitem->>'poin', '') ~ '^\d+(\.\d+)?$' THEN
        v_poin := GREATEST(0::numeric, LEAST(v_soal.poin, (v_kitem->>'poin')::numeric));
      END IF;
      v_cat := left(btrim(COALESCE(v_kitem->>'catatan', v_cat)), 500);
      v_benar := CASE
        WHEN v_soal.poin > 0 AND v_poin >= v_soal.poin THEN true
        WHEN v_soal.poin > 0 AND v_poin = 0 THEN false
        ELSE NULL
      END;
    END IF;

    v_penilaian := v_penilaian || jsonb_build_object(
      v_soal.id::text,
      jsonb_build_object(
        'poin', v_poin,
        'maks', v_soal.poin,
        'benar', v_benar,
        'manual', v_manual,
        'catatan', v_cat
      )
    );

    IF v_soal.poin > 0 THEN
      IF v_soal.tipe = 'essay' OR v_manual THEN
        v_skor_maks := v_skor_maks + v_soal.poin;
        v_skor_manual := v_skor_manual + v_poin;
      ELSE
        -- Hanya hitung skor_maks untuk soal auto yang memang dinilai
        IF v_benar IS NOT NULL OR v_soal.tipe = 'bobot' THEN
          v_skor_maks := v_skor_maks + v_soal.poin;
          v_skor_auto := v_skor_auto + v_poin;
        END IF;
      END IF;
    END IF;
  END LOOP;

  v_status := CASE WHEN COALESCE(p_selesai, true) THEN 'selesai' ELSE 'menunggu_koreksi' END;

  UPDATE public.osis_tes_hasil
     SET penilaian       = v_penilaian,
         skor_otomatis   = v_skor_auto,
         skor_manual     = v_skor_manual,
         skor_total      = v_skor_auto + v_skor_manual,
         skor_maks       = v_skor_maks,
         status          = v_status,
         catatan_koreksi = left(btrim(COALESCE(p_catatan, '')), 1000),
         dikoreksi_oleh  = p_user_id,
         updated_at      = now()
   WHERE id = p_hasil_id;

  RETURN jsonb_build_object(
    'ok', true,
    'id', p_hasil_id,
    'skor_total', v_skor_auto + v_skor_manual,
    'skor_maks', v_skor_maks,
    'status', v_status
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.hapus_tes_hasil(
  p_user_id  bigint,
  p_hasil_id bigint
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_ang bigint;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    p_user_id := public.osis_id_dari_auth();
    IF p_user_id IS NULL THEN RETURN 'ERR_NO_AUTH'; END IF;
  END IF;
  IF NOT public.osis_bisa(p_user_id, 'tes') THEN RETURN 'ERR_NO_AUTH'; END IF;

  SELECT angkatan_id INTO v_ang FROM public.osis_tes_hasil WHERE id = p_hasil_id;
  IF NOT FOUND THEN RETURN 'ERR_NOT_FOUND'; END IF;
  IF NOT public.osis_boleh_angkatan(p_user_id, v_ang) THEN RETURN 'ERR_NO_AUTH'; END IF;

  DELETE FROM public.osis_tes_hasil WHERE id = p_hasil_id;
  RETURN 'OK';
END;
$function$;

