-- ================= 8. SIDEBAR MENU (GRUP UMUM) =================
-- Sisipkan "Tes & Kuis" ke dalam grup "Umum" agar tetap berurutan (tidak membelah grup).
DO $$
DECLARE
  v_raw      text;
  v_arr      jsonb;
  v_baru     jsonb := '[]'::jsonb;
  v_el       jsonb;
  v_last_idx integer := -1;
  v_idx      integer := 0;
  v_tes_item jsonb := jsonb_build_object(
    'href', 'tes',
    'icon', 'fa-solid fa-clipboard-question',
    'label', 'Tes & Kuis',
    'super', false,
    'grup', 'Umum',
    'populer', false
  );
BEGIN
  SELECT nilai INTO v_raw FROM public.site_content WHERE kunci = 'sidebar_menu';
  IF v_raw IS NULL THEN RETURN; END IF;
  BEGIN
    v_arr := v_raw::jsonb;
  EXCEPTION WHEN others THEN
    RETURN;
  END;
  IF jsonb_typeof(v_arr) <> 'array' THEN RETURN; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(v_arr) AS e
     WHERE lower(COALESCE(e->>'href', '')) IN ('tes', 'tes.html')
  ) THEN
    RETURN;
  END IF;

  FOR v_el IN SELECT * FROM jsonb_array_elements(v_arr) LOOP
    v_idx := v_idx + 1;
    IF lower(btrim(COALESCE(v_el->>'grup', ''))) = 'umum' THEN
      v_last_idx := v_idx;
    END IF;
  END LOOP;

  IF v_last_idx <= 0 THEN
    v_baru := v_arr || jsonb_build_array(v_tes_item);
  ELSE
    v_idx := 0;
    FOR v_el IN SELECT * FROM jsonb_array_elements(v_arr) LOOP
      v_idx := v_idx + 1;
      v_baru := v_baru || jsonb_build_array(v_el);
      IF v_idx = v_last_idx THEN
        v_baru := v_baru || jsonb_build_array(v_tes_item);
      END IF;
    END LOOP;
  END IF;

  UPDATE public.site_content
     SET nilai = v_baru::text,
         updated_at = now()
   WHERE kunci = 'sidebar_menu';
END $$;

COMMIT;
