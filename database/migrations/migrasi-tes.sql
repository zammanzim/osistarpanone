-- Fitur:
--   - Tabel osis_tes, osis_tes_soal, osis_tes_hasil (scoped per angkatan_id)
--   - Tipe soal: pg, multi, bs, isian, essay, skala, bobot (Likert/poin per opsi)
--   - RLS aktif + REVOKE SELECT langsung (akses via RPC SECURITY DEFINER)
--   - Kunci jawaban & pembahasan disembunyikan dari peserta sebelum selesai
--     (dan tetap tersembunyi bila tampil_kunci = false)
--   - Penilaian otomatis objektif + koreksi manual essay di sisi server
--   - Update menu sidebar di site_content (grup Umum, hanya jika belum ada)
